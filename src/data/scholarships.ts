export function getScholarshipBySlug(slug: string): Scholarship | undefined {
  return SCHOLARSHIPS.find((s) => s.slug === slug);
}

export function getScholarshipsByCategory(categorySlug: string): Scholarship[] {
  return SCHOLARSHIPS.filter(
    (s) => s.category === categorySlug || s.secondaryCategories?.includes(categorySlug as any)
  );
}

export function getScholarshipsByUniversity(universitySlug: string): Scholarship[] {
  return SCHOLARSHIPS.filter((s) => s.universitySlug === universitySlug);
}
